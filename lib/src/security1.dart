/// Security 1 of the provisioning protocol: Curve25519 (X25519) key
/// exchange, AES-CTR encryption and an optional proof of possession.
///
/// Use it with devices whose firmware is built with `WIFI_PROV_SECURITY_1`
/// (`protocomm_security1`), passing in [pop] the proof of possession that
/// the device expects, if any.
///
/// The handshake has two rounds, driven by [securitySession]:
///
/// 1. [setup0Request] sends a new client public key, and [setup0Response]
///    reads the device's public key and random. The session key is the
///    X25519 shared secret, XORed with the SHA-256 hash of [pop] when there
///    is one, and the device random is the AES-CTR nonce.
/// 2. [setup1Request] sends the device's public key encrypted with the
///    session key, and [setup1Response] checks that the device answers with
///    the client's public key encrypted the same way. With a wrong [pop] the
///    keys differ, and the device rejects session command 1.
///
/// The AES-CTR cipher runs in the plugin's native code (Android and iOS),
/// which keeps a single cipher: each handshake replaces the one set up by
/// the previous handshake, so only one [Security1] session can be used at a
/// time. Encryption and decryption share the same counter, as on the device,
/// so requests must be encrypted and responses decrypted in the order they
/// are exchanged, which [EspProv] does.
///
/// An instance holds the state of one handshake and does not reset after a
/// failed one: create a new instance to try again.
///
/// ```dart
/// final prov = EspProv(
///   transport: myTransport,
///   security: Security1(pop: 'abcd1234'),
/// );
/// ```
class Security1 implements ProvSecurity {
  /// The proof of possession, or `null` if the device does not use one.
  ///
  /// It is UTF-8 encoded and hashed with SHA-256 to derive the session key.
  final String? pop;

  /// Whether to print each handshake step for debugging. It only prints in
  /// debug builds, and the output includes [pop] and the session key.
  final bool verbose;

  /// The next step of the handshake. It starts at [SecurityState.request1]
  /// unless another state is passed to the constructor.
  SecurityState sessionState;

  /// The client's X25519 key pair, generated by [setup0Request].
  ///
  /// Reading it before [setup0Request] has run throws a
  /// `LateInitializationError`.
  late SimpleKeyPair clientKey;

  /// The device's X25519 public key, read by [setup0Response].
  ///
  /// Reading it before [setup0Response] has run throws a
  /// `LateInitializationError`.
  late SimplePublicKey devicePublicKey;

  /// The device random, read by [setup0Response] and used as the AES-CTR
  /// nonce.
  ///
  /// Reading it before [setup0Response] has run throws a
  /// `LateInitializationError`.
  late Uint8List deviceRandom;

  /// The native AES-CTR cipher that [encrypt] and [decrypt] use. It is an
  /// implementation detail and is not meant to be used directly.
  Crypt crypt = Crypt();

  /// The X25519 algorithm used for the key exchange.
  X25519 x25519 = X25519();

  /// The SHA-256 algorithm used to hash [pop].
  Sha256 sha256 = Sha256();

  /// Creates a Security 1 scheme with the proof of possession [pop] that
  /// starts its handshake at [sessionState].
  Security1(
      {this.pop,
      this.sessionState = SecurityState.request1,
      this.verbose = false});

  void _verbose(dynamic data) {
    if (verbose) {
      if (kDebugMode) {
        print('+++ $data +++');
      }
    }
  }

  /// Encrypts [data] with the session key (AES-CTR).
  ///
  /// The session key is set up by [setup0Response], so it must not be called
  /// before the handshake has reached that point.
  @override
  Future<Uint8List> encrypt(Uint8List data) async {
    _verbose('raw before process ${data.toString()}');
    return crypt.crypt(data);
  }

  /// Decrypts [data] with the session key.
  ///
  /// In AES-CTR decryption is the same operation as encryption, so it calls
  /// [encrypt], which advances the same counter.
  @override
  Future<Uint8List> decrypt(Uint8List data) async {
    return encrypt(data);
  }

  Future<void> _generateKey() async {
    clientKey = await x25519.newKeyPair();
  }

  Uint8List _xor(Uint8List a, Uint8List b) {
    Uint8List ret = Uint8List(max(a.length, b.length));
    for (var i = 0; i < max(a.length, b.length); i++) {
      final c = i < a.length ? a[i] : 0;
      final d = i < b.length ? b[i] : 0;
      ret[i] = (c ^ d);
    }
    return ret;
  }

  /// Runs the next step of the Security 1 handshake, as described in
  /// [ProvSecurity.securitySession].
  ///
  /// Depending on [sessionState], it returns [setup0Request], runs
  /// [setup0Response] and returns [setup1Request], or runs [setup1Response]
  /// and returns `null`. [sessionState] moves to the next step before the
  /// response is checked, so it advances even if the check throws. In
  /// [SecurityState.finish] it returns `null`.
  @override
  Future<SessionData?> securitySession(SessionData responseData) async {
    if (sessionState == SecurityState.request1) {
      sessionState = SecurityState.response1Request2;
      return await setup0Request();
    }
    if (sessionState == SecurityState.response1Request2) {
      sessionState = SecurityState.response2;
      await setup0Response(responseData);
      return await setup1Request(responseData);
    }
    if (sessionState == SecurityState.response2) {
      sessionState = SecurityState.finish;
      await setup1Response(responseData);
      return null;
    }
    if (sessionState == SecurityState.finish) {
      // Session is already established. Returning null signals to
      // [EspProv.establishSession] that there is nothing left to negotiate,
      // so the loop exits with [EstablishSessionStatus.connected] without
      // performing any extra BLE round-trip. This makes the call idempotent
      // and lets callers invoke `establishSession()` defensively without
      // paying the cost of the handshake every time.
      return null;
    }
    throw Exception('Unexpected state');
  }

  /// Generates a new [clientKey] and returns session command 0, which
  /// carries the client's public key.
  Future<SessionData> setup0Request() async {
    _verbose('setup0Request');
    var setupRequest = SessionData();

    setupRequest.secVer = SecSchemeVersion.SecScheme1;
    await _generateKey();
    SessionCmd0 sc0 = SessionCmd0();
    List<int> temp =
        await clientKey.extractPublicKey().then((value) => value.bytes);
    sc0.clientPubkey = temp;
    Sec1Payload sec1 = Sec1Payload();
    sec1.sc0 = sc0;
    setupRequest.sec1 = sec1;
    _verbose('setup0Request: clientPubkey = ${temp.toString()}');
    return setupRequest;
  }

  /// Reads session response 0 and sets up the session key.
  ///
  /// It stores the device's public key in [devicePublicKey] and its random
  /// in [deviceRandom], derives the session key from the X25519 shared
  /// secret and [pop], and initialises the native cipher with it. Returns
  /// [responseData].
  ///
  /// Throws an [Exception] if [responseData] does not use Security 1.
  Future<SessionData> setup0Response(SessionData responseData) async {
    SessionData setupResp = responseData;
    if (setupResp.secVer != SecSchemeVersion.SecScheme1) {
      throw Exception('Invalid sec scheme');
    }
    devicePublicKey = SimplePublicKey(setupResp.sec1.sr0.devicePubkey,
        type: x25519.keyPairType);
    deviceRandom = Uint8List.fromList(setupResp.sec1.sr0.deviceRandom);

    _verbose(
        'setup0Response:Device public key ${devicePublicKey.bytes.toString()}');
    _verbose('setup0Response:Device random ${deviceRandom.toString()}');

    final sharedKey = await x25519.sharedSecretKey(
        keyPair: clientKey, remotePublicKey: devicePublicKey);
    var sharedK = await sharedKey.extractBytes();
    _verbose('setup0Response: Shared key calculated: ${sharedK.toString()}');
    if (pop != null) {
      var sink = sha256.newHashSink();
      sink.add(utf8.encode(pop!));
      sink.close();
      final hash = await sink.hash();
      sharedK =
          _xor(Uint8List.fromList(sharedK), Uint8List.fromList(hash.bytes));
      _verbose(
          'setup0Response: pop: $pop, hash: ${hash.bytes.toString()} sharedK: ${sharedK.toString()}');
    }
    await crypt.init(Uint8List.fromList(sharedK), deviceRandom);
    _verbose(
        'setup0Response: cipherSecretKey: ${sharedK.toString()} cipherNonce: ${deviceRandom.toString()}');
    return setupResp;
  }

  /// Returns session command 1, which carries the device's public key
  /// encrypted with the session key as the client verification data.
  ///
  /// [responseData] is not used.
  Future<SessionData> setup1Request(SessionData responseData) async {
    _verbose('setup1Request ${devicePublicKey.bytes.toString()}');
    var clientVerify = await encrypt(Uint8List.fromList(devicePublicKey.bytes));

    _verbose('client verify ${clientVerify.toString()}');
    var setupRequest = SessionData();
    setupRequest.secVer = SecSchemeVersion.SecScheme1;
    Sec1Payload sec1 = Sec1Payload();
    sec1.msg = Sec1MsgType.Session_Command1;
    SessionCmd1 sc1 = SessionCmd1();
    sc1.clientVerifyData = clientVerify;
    sec1.sc1 = sc1;
    setupRequest.sec1 = sec1;
    return setupRequest;
  }

  /// Reads session response 1 and checks the device verification data.
  ///
  /// The device must send back the client's public key encrypted with the
  /// session key. Returns `null` when it matches.
  ///
  /// Throws an [Exception] if [responseData] does not use Security 1 or the
  /// verification data does not match.
  Future<SessionData?> setup1Response(SessionData responseData) async {
    _verbose('setup1Response');
    var setupResp = responseData;
    if (setupResp.secVer == SecSchemeVersion.SecScheme1) {
      final deviceVerify = setupResp.sec1.sr1.deviceVerifyData;
      _verbose('Device verify: ${deviceVerify.toString()}');
      final encClientPubkey = await decrypt(
          Uint8List.fromList(setupResp.sec1.sr1.deviceVerifyData));
      _verbose('Enc client pubkey: ${encClientPubkey.toString()}');
      Function eq = const ListEquality().equals;
      List<int> temp =
          await clientKey.extractPublicKey().then((value) => value.bytes);
      if (!eq(encClientPubkey, temp)) {
        throw Exception('Mismatch in device verify');
      }
      return null;
    }
    throw Exception('Unsupported security protocol');
  }
}
